namespace Endatix.IntegrationTests;

/// <summary>
/// The API never runs on a signing key it did not choose: it refuses to start on a missing, short or publicly known
/// key, except in Development with no key at all, where it uses a random key for the process. Every key here is
/// generated by the test; no real key value appears in this file or its output.
/// </summary>
[Collection(nameof(EndatixIntegrationTestCollection))]
[Trait("Category", "CriticalPath")]
[Trait("Priority", "P0")]
public sealed class SigningKeyStartupFlowTests(EndatixIntegrationWebHostFixture fixture)
{
    private const string SEED_PASSWORD = "Password123!";

    [Fact]
    public void The_api_host_ships_no_signing_key()
    {
        // Arrange
        var contentRoot = fixture.Factory.Services.GetRequiredService<IWebHostEnvironment>().ContentRootPath;

        // Act
        var shipped = new ConfigurationBuilder()
            .SetBasePath(contentRoot)
            .AddJsonFile("appsettings.json", optional: false)
            .Build();

        // Assert
        Assert.True(string.IsNullOrEmpty(shipped[SigningKeyRule.SUBMISSION_KEY_PATH]), "appsettings.json ships a submission key");
        Assert.True(string.IsNullOrEmpty(shipped[SigningKeyRule.JWT_KEY_PATH]), "appsettings.json ships a sign-in key");
        Assert.True(string.IsNullOrEmpty(shipped[SigningKeyRule.LEGACY_JWT_KEY_PATH]), "appsettings.json ships a legacy sign-in key");
    }

    [Theory]
    [InlineData(SigningKeyRule.SUBMISSION_KEY_PATH, "")]
    [InlineData(SigningKeyRule.SUBMISSION_KEY_PATH, "short-submission-key")]
    [InlineData(SigningKeyRule.JWT_KEY_PATH, "")]
    [InlineData(SigningKeyRule.JWT_KEY_PATH, "short-sign-in-key")]
    public async Task A_host_outside_development_refuses_to_start_on_a_missing_or_short_key(string keyPath, string key)
    {
        // Act
        var failure = await StartFailureAsync(builder => builder.UseSetting(keyPath, key));

        // Assert
        Assert.NotNull(failure);
        Assert.Contains(keyPath.Replace(":", "__", StringComparison.Ordinal), failure.Message, StringComparison.Ordinal);
    }

    [Fact]
    public async Task A_host_outside_development_refuses_to_start_on_a_deny_listed_submission_key()
    {
        // Arrange: a key that stands in for a published one, deny-listed for this host only.
        var publicKey = RandomKey();
        var denied = new HashSet<string> { SigningKeyRule.Hash(publicKey) };

        // Act
        var failure = await StartFailureAsync(builder => builder
            .UseSetting(SigningKeyRule.SUBMISSION_KEY_PATH, publicKey)
            .ConfigureTestServices(services =>
            {
                services.RemoveAll<IValidateOptions<SubmissionAccessTokenOptions>>();
                services.AddSingleton<IValidateOptions<SubmissionAccessTokenOptions>>(
                    new SigningKeyOptionsValidator<SubmissionAccessTokenOptions>(SigningKeyValidation.SubmissionKeys, denied));
            }));

        // Assert
        Assert.NotNull(failure);
        Assert.Contains("publicly known", failure.Message, StringComparison.Ordinal);
        Assert.DoesNotContain(publicKey, failure.Message, StringComparison.Ordinal);
    }

    [Fact]
    public async Task A_development_host_without_keys_starts_and_its_sign_in_tokens_work()
    {
        // Arrange
        await using var factory = SecondHost(builder => builder
            .UseEnvironment(Environments.Development)
            .UseSetting(SigningKeyRule.SUBMISSION_KEY_PATH, string.Empty)
            .UseSetting(SigningKeyRule.JWT_KEY_PATH, string.Empty)
            .UseSetting(SigningKeyRule.LEGACY_JWT_KEY_PATH, string.Empty));

        // Act
        var status = await SignInAndListFormsAsync(factory);

        // Assert
        Assert.Equal(HttpStatusCode.OK, status);
        await using var scope = factory.Services.CreateAsyncScope();
        _ = scope.ServiceProvider.GetRequiredService<ISubmissionAccessTokenService>();
    }

    [Fact]
    public async Task A_host_with_only_the_legacy_sign_in_key_starts_and_its_sign_in_tokens_work()
    {
        // Arrange
        await using var factory = SecondHost(builder => builder
            .UseSetting(SigningKeyRule.JWT_KEY_PATH, string.Empty)
            .UseSetting(SigningKeyRule.LEGACY_JWT_KEY_PATH, RandomKey()));

        // Act
        var status = await SignInAndListFormsAsync(factory);

        // Assert
        Assert.Equal(HttpStatusCode.OK, status);
    }

    /// <summary>A token signed under any key but the host's own is refused.</summary>
    [Fact]
    public async Task A_token_signed_with_another_key_is_refused()
    {
        // Arrange
        var (formId, submissionId) = await SubmissionOnAPrivateFormAsync();
        using var anonymous = fixture.Factory.CreateClient();
        var forged = Forge(RandomKey(), submissionId, SubmissionAccessTokenPermissions.View);

        // Act
        using var response = await anonymous.GetAsync($"/api/forms/{formId}/submissions/by-access-token/{forged}", Ct);

        // Assert
        Assert.Equal(HttpStatusCode.BadRequest, response.StatusCode);
    }

    private static CancellationToken Ct => TestContext.Current.CancellationToken;

    /// <summary>A second host on the collection's database (Staging unless the builder says otherwise).</summary>
    private WebApplicationFactory<EndatixWebHost::Program> SecondHost(Action<IWebHostBuilder> configure) =>
        new EndatixWebApplicationFactory(fixture.Database.ConnectionString, fixture.Database.Provider)
            .WithWebHostBuilder(configure);

    /// <summary>Signs in as the tenant admin on <paramref name="factory"/> and lists forms with the token it issued.</summary>
    private async Task<HttpStatusCode> SignInAndListFormsAsync(WebApplicationFactory<EndatixWebHost::Program> factory)
    {
        var world = await fixture.PrepareWorldAsync(IntegrationWorldOptions.SingleTenant with { DefaultPassword = SEED_PASSWORD }, Ct);
        var admin = world.Tenants[0].Admin;
        using var client = factory.CreateClient();
        using var login = await client.PostAsJsonAsync("/api/auth/login", new { email = admin.Email, password = SEED_PASSWORD }, Ct);
        login.EnsureSuccessStatusCode();
        var accessToken = (await login.Content.ReadFromJsonAsync<JsonElement>(Ct)).GetProperty("accessToken").GetString();
        client.DefaultRequestHeaders.Authorization = new AuthenticationHeaderValue("Bearer", accessToken);
        using var forms = await client.GetAsync("/api/forms", Ct);
        return forms.StatusCode;
    }

    private static string RandomKey() => Convert.ToBase64String(RandomNumberGenerator.GetBytes(48));

    /// <summary>Starts a second host on the collection's database (Staging); returns why it refused to start, or null.</summary>
    private async Task<OptionsValidationException?> StartFailureAsync(Action<IWebHostBuilder> configure)
    {
        await using var factory = SecondHost(configure);
        try
        {
            _ = factory.Services;
            return null;
        }
        catch (Exception exception)
        {
            return FindValidationFailure(exception);
        }
    }

    private static OptionsValidationException? FindValidationFailure(Exception? exception) => exception switch
    {
        null => null,
        OptionsValidationException validation => validation,
        AggregateException aggregate => aggregate.InnerExceptions.Select(FindValidationFailure).FirstOrDefault(found => found is not null),
        _ => FindValidationFailure(exception.InnerException),
    };

    /// <summary>A forged token: <c>{id}.{expiry}.{codes}.{signature}</c>, HMAC-SHA256, base64url, first 16 chars.</summary>
    private static string Forge(string key, long submissionId, params SubmissionAccessTokenPermissions.AccessTokenPermission[] permissions)
    {
        var expiry = DateTimeOffset.UtcNow.AddHours(1).ToUnixTimeSeconds().ToString(CultureInfo.InvariantCulture);
        var codes = SubmissionAccessTokenPermissions.ToCodesString(permissions);
        var id = submissionId.ToString(CultureInfo.InvariantCulture);
        var mac = HMACSHA256.HashData(Encoding.UTF8.GetBytes(key), Encoding.UTF8.GetBytes(string.Join('\n', id, expiry, codes)));
        var signature = Convert.ToBase64String(mac).Replace('+', '-').Replace('/', '_').TrimEnd('=')[..16];
        return $"{id}.{expiry}.{codes}.{signature}";
    }

    /// <summary>A complete submission on an enabled form that is not public, made by the tenant admin.</summary>
    private async Task<(string FormId, long SubmissionId)> SubmissionOnAPrivateFormAsync()
    {
        var world = await fixture.PrepareWorldAsync(IntegrationWorldOptions.SingleTenant with { DefaultPassword = SEED_PASSWORD }, Ct);
        using var admin = await world.AsAsync(TestPersona.TenantAdmin, cancellationToken: Ct);

        using var form = await admin.PostAsJsonAsync(
            "/api/forms",
            new
            {
                name = $"private-form-{Guid.NewGuid():N}",
                isEnabled = true,
                formDefinitionJsonData = """{"pages":[{"name":"page1","elements":[{"type":"text","name":"q1"}]}]}""",
            },
            Ct);
        form.EnsureSuccessStatusCode();
        var formId = (await form.Content.ReadFromJsonAsync<JsonElement>(Ct)).GetProperty("id").GetString()!;

        using var created = await admin.PostAsJsonAsync(
            $"/api/forms/{formId}/submissions/onbehalf",
            new { isComplete = true, jsonData = """{"q1":"answer"}""" },
            Ct);
        created.EnsureSuccessStatusCode();
        var submissionId = long.Parse(
            (await created.Content.ReadFromJsonAsync<JsonElement>(Ct)).GetProperty("id").GetString()!,
            CultureInfo.InvariantCulture);
        return (formId, submissionId);
    }
}
